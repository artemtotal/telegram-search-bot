"""Одне оголошення — одне повідомлення людині за обхід.

Фільтри зберігаються окремим записом на кожне джерело, і в однієї людини їх
цілком легально буває кілька: ширший пошук на всякий випадок і вужчий —
основний. Доставка ж рахувалася парою (фільтр, оголошення), тож квартира, що
підходила під два її фільтри, приходила двома однаковими повідомленнями
поспіль. Найгірше це виглядало на випадкових дублях самого фільтра: 10.09.2026
одна однокімнатна прилетіла користувачу вісім разів за секунду — по разу з
кожної з восьми копій того самого фільтра.

Позначку про доставку далі ставимо КОЖНОМУ фільтру, що збігся, а не лише
тому, з якого пішло повідомлення: інакше решта збігів вважалися б
ненадісланими й та сама квартира пішла б повторно вже наступного обходу.
"""

from typing import Set, Tuple


class PerUserDedup:
    """Пам'ятає, що в межах одного обходу вже пішло цій людині."""

    def __init__(self) -> None:
        self._seen: Set[Tuple[int, str]] = set()

    def claim(self, user_id, listing_key) -> bool:
        """True — надсилати можна (це перший збіг цієї людини з оголошенням).

        False — оголошення їй уже пішло з іншого фільтра цього ж обходу.
        """
        key = (int(user_id), str(listing_key))
        if key in self._seen:
            return False
        self._seen.add(key)
        return True
